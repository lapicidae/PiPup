package nl.rogro82.pipup.ui

import org.json.JSONArray
import org.json.JSONObject

/**
 * Metadata for an open-source license entry parsed from AboutLibraries JSON.
 */
data class LicenseInfo(
    val name: String,
    val url: String?,
    val content: String?,
)

/**
 * Metadata for an open-source library or grouped library family parsed from AboutLibraries JSON.
 */
data class LibraryInfo(
    val uniqueId: String,
    val name: String,
    val version: String?,
    val description: String?,
    val author: String?,
    val website: String?,
    val licenses: List<LicenseInfo>,
    val artifacts: List<String> = listOf(OpenSourceLicenses.formatArtifact(uniqueId, version)),
)

/**
 * Lightweight parser and generic family grouper for `aboutlibraries.json` generated by the
 * AboutLibraries Gradle plugin. Uses `org.json` directly to avoid extra runtime dependencies.
 */
object OpenSourceLicenses {

    private const val ANDROIDX_FAMILY = "androidx"
    private const val ANDROIDX_PREFIX = "androidx."
    private const val ANDROIDX_MEDIA3_GROUP = "androidx.media3"
    private const val ANDROIDX_DISPLAY_NAME = "AndroidX (Jetpack)"
    private const val ANDROIDX_WEBSITE = "https://developer.android.com/jetpack/androidx"
    private val WORD_SPLIT_REGEX = Regex("[\\s-]+")

    /**
     * Parses raw `aboutlibraries.json` into a case-insensitively sorted list of [LibraryInfo].
     * Returns an empty list if [json] is blank or malformed.
     */
    fun parse(json: String): List<LibraryInfo> {
        if (json.isBlank()) return emptyList()
        return try {
            val root = JSONObject(json)
            val licenseMap = parseLicenseMap(root.optJSONObject("licenses"))
            val libraries = root.optJSONArray("libraries") ?: return emptyList()
            parseLibraries(libraries, licenseMap).sortedByName()
        } catch (_: Exception) {
            emptyList()
        }
    }

    /**
     * Parses `aboutlibraries.json` and groups multi-module artifacts sharing the same family and
     * identical licenses into clean single entries while retaining all artifact coordinates.
     */
    fun parseGrouped(json: String): List<LibraryInfo> = group(parse(json))

    /**
     * Groups [libraries] by Maven group family and identical license set.
     *
     * Rules are completely generic:
     * - All `androidx.*` platform artifacts (except `androidx.media3`) sharing identical licenses
     *   are combined under [ANDROIDX_DISPLAY_NAME].
     * - Any other multi-module Maven group sharing identical licenses (e.g. `androidx.media3`,
     *   `com.github.bumptech.glide`, `org.jetbrains.kotlinx`) is combined into one entry.
     * - Single-artifact libraries remain untouched.
     */
    fun group(libraries: List<LibraryInfo>): List<LibraryInfo> {
        if (libraries.isEmpty()) return emptyList()
        return libraries
            .groupBy { bucketKey(it) }
            .map { (key, items) ->
                if (items.size == 1) items.first() else mergeGroup(key.first, items)
            }
            .sortedByName()
    }

    /**
     * Formats an artifact coordinate with its optional version for detail attribution lists.
     */
    fun formatArtifact(uniqueId: String, version: String?): String =
        if (version.isNullOrBlank()) uniqueId else "$uniqueId:$version"

    private fun bucketKey(library: LibraryInfo): Pair<String, String> {
        val groupId = library.uniqueId.substringBefore(':', "")
        val licenseKey = library.licenses.map { it.name }.sorted().joinToString("|")
        val familyKey = when {
            groupId.startsWith(ANDROIDX_PREFIX) && groupId != ANDROIDX_MEDIA3_GROUP -> ANDROIDX_FAMILY
            groupId.isNotBlank() -> groupId
            else -> library.uniqueId
        }
        return familyKey to licenseKey
    }

    private fun mergeGroup(familyKey: String, items: List<LibraryInfo>): LibraryInfo {
        val artifacts = items.flatMap { it.artifacts }.distinct().sorted()
        if (familyKey == ANDROIDX_FAMILY) {
            return LibraryInfo(
                uniqueId = "$ANDROIDX_FAMILY.*",
                name = ANDROIDX_DISPLAY_NAME,
                version = null,
                description = null,
                author = items.firstNotNullOfOrNull { it.author },
                website = ANDROIDX_WEBSITE,
                licenses = items.first().licenses,
                artifacts = artifacts,
            )
        }

        val lastSegment = familyKey.substringAfterLast('.')
        val primary = findPrimaryArtifact(items, lastSegment)
        val distinctVersions = items.mapNotNull { it.version }.distinct()
        val version = when {
            distinctVersions.size == 1 -> distinctVersions.first()
            primary?.version != null -> primary.version
            else -> null
        }

        return LibraryInfo(
            uniqueId = "$familyKey:*",
            name = resolveGroupName(primary, items, lastSegment),
            version = version,
            description = primary?.description,
            author = primary?.author ?: items.firstNotNullOfOrNull { it.author },
            website = primary?.website ?: items.firstNotNullOfOrNull { it.website },
            licenses = items.first().licenses,
            artifacts = artifacts,
        )
    }

    private fun findPrimaryArtifact(items: List<LibraryInfo>, lastSegment: String): LibraryInfo? {
        val preferredIds = listOf(lastSegment, "$lastSegment-android", "$lastSegment-core")
        for (preferred in preferredIds) {
            val match = items.firstOrNull {
                it.uniqueId.substringAfter(':', "").equals(preferred, ignoreCase = true)
            }
            if (match != null) return match
        }
        return null
    }

    private fun resolveGroupName(
        primary: LibraryInfo?,
        items: List<LibraryInfo>,
        lastSegment: String,
    ): String {
        primary?.name?.let { return it }
        val commonPrefix = longestCommonWordPrefix(items.map { it.name })
        if (commonPrefix.isNotEmpty()) {
            return if (commonPrefix.all { it.isLowerCase() || !it.isLetter() }) {
                commonPrefix.replaceFirstChar { it.uppercaseChar() }
            } else {
                commonPrefix
            }
        }
        return lastSegment.replaceFirstChar { it.uppercaseChar() }
    }

    private fun longestCommonWordPrefix(names: List<String>): String {
        val tokenLists = names.map { it.split(WORD_SPLIT_REGEX).filter(String::isNotBlank) }
        val first = tokenLists.firstOrNull() ?: return ""
        val prefix = mutableListOf<String>()
        for (index in first.indices) {
            val candidate = first[index]
            if (tokenLists.all { index < it.size && it[index].equals(candidate, ignoreCase = true) }) {
                prefix.add(candidate)
            } else {
                break
            }
        }
        return prefix.joinToString(" ")
    }

    private fun List<LibraryInfo>.sortedByName(): List<LibraryInfo> =
        sortedWith(compareBy(String.CASE_INSENSITIVE_ORDER, LibraryInfo::name).thenBy(LibraryInfo::uniqueId))

    private fun parseLicenseMap(licensesObj: JSONObject?): Map<String, LicenseInfo> {
        if (licensesObj == null) return emptyMap()
        val result = mutableMapOf<String, LicenseInfo>()
        val keys = licensesObj.keys()
        while (keys.hasNext()) {
            val key = keys.next()
            val obj = licensesObj.optJSONObject(key) ?: continue
            val name = obj.optNonBlankString("name") ?: obj.optNonBlankString("spdxId") ?: key
            result[key] = LicenseInfo(
                name = name,
                url = obj.optNonBlankString("url"),
                content = obj.optNonBlankString("content"),
            )
        }
        return result
    }

    private fun parseLibraries(array: JSONArray, licenseMap: Map<String, LicenseInfo>): List<LibraryInfo> {
        val result = ArrayList<LibraryInfo>(array.length())
        for (i in 0 until array.length()) {
            val obj = array.optJSONObject(i) ?: continue
            val uniqueId = obj.optNonBlankString("uniqueId") ?: continue
            val name = obj.optNonBlankString("name") ?: uniqueId
            val version = obj.optNonBlankString("artifactVersion")
            val author = parseAuthor(obj)
            val website = obj.optNonBlankString("website")
                ?: obj.optJSONObject("scm")?.optNonBlankString("url")
            val licenses = parseLibraryLicenses(obj.optJSONArray("licenses"), licenseMap)
            result.add(
                LibraryInfo(
                    uniqueId = uniqueId,
                    name = name,
                    version = version,
                    description = obj.optNonBlankString("description"),
                    author = author,
                    website = website,
                    licenses = licenses,
                ),
            )
        }
        return result
    }

    private fun parseAuthor(libObj: JSONObject): String? {
        libObj.optJSONObject("organization")?.optNonBlankString("name")?.let { return it }
        val devs = libObj.optJSONArray("developers") ?: return null
        val names = mutableListOf<String>()
        for (i in 0 until devs.length()) {
            devs.optJSONObject(i)?.optNonBlankString("name")?.let { names.add(it) }
        }
        return names.takeIf { it.isNotEmpty() }?.joinToString(", ")
    }

    private fun parseLibraryLicenses(
        keys: JSONArray?,
        licenseMap: Map<String, LicenseInfo>,
    ): List<LicenseInfo> {
        if (keys == null || keys.length() == 0) return emptyList()
        val result = ArrayList<LicenseInfo>(keys.length())
        for (i in 0 until keys.length()) {
            val key = keys.optString(i, "").trim()
            if (key.isNotEmpty()) {
                result.add(licenseMap[key] ?: LicenseInfo(name = key, url = null, content = null))
            }
        }
        return result
    }

    private fun JSONObject.optNonBlankString(key: String): String? {
        if (!has(key) || isNull(key)) return null
        return optString(key, "").trim().takeIf { it.isNotEmpty() }
    }
}
